package gui

import "image"

// Canvas — то, чем рисуется окно.
//
// # Зачем интерфейс, а не прямые вызовы GDI+
//
// Отрисовка окна — единственная часть клиента, которую нельзя проверить
// обычным тестом: «налезло», «съехало», «не того цвета» видно только
// глазами. Интерфейс разрывает эту связь: сам рисунок собирается здесь,
// на чистом Go, а куда лягут пиксели — дело реализации.
//
// Реализаций две. Оконная (cmd/masquevpn-win) рисует через GDI+. Проверочная
// (svg_test.go) выводит тот же рисунок в SVG, который можно открыть и
// посмотреть на любой машине. Важно, что рисует их один и тот же код: будь
// проверочная версия отдельной, она показывала бы не то, что увидит
// человек, а то, что о ней думает её автор.
//
// # Почему в интерфейсе есть пиксели
//
// Почти всё задаётся в логических точках, и масштаб экрана — забота
// реализации. Исключение одно: столбики графика. Их ширина делится на
// тридцать, и при масштабе 125% деление в точках даёт дробь — столбики
// разъезжаются на пиксель, а на ровном ряду это сразу видно. Поэтому график
// считает пиксели сам, для чего ему нужны Scale и FillPixels.
type Canvas interface {
	// Clear заливает всё окно.
	Clear(c Color)
	// Fill закрашивает прямоугольник.
	Fill(r Rect, c Color)
	// Round заливает скруглённый прямоугольник.
	Round(r Rect, radius int32, c Color)
	// RoundGradient заливает его вертикальным градиентом.
	RoundGradient(r Rect, radius int32, top, bottom Color)
	// Border рисует рамку толщиной w вокруг скруглённого прямоугольника.
	Border(r Rect, radius int32, c Color, w int32)
	// Dot рисует круг (или эллипс) по описанному прямоугольнику.
	Dot(r Rect, c Color)
	// Quad заливает четырёхугольник по точкам, заданным в пикселях: им
	// рисуются диагонали креста, перья стрелок и уголки.
	Quad(pts [4][2]int32, c Color)
	// Text рисует строку внутри прямоугольника, по вертикали — посередине.
	Text(s string, f Font, r Rect, c Color, a Align)
	// Width измеряет строку в логических точках.
	Width(s string, f Font) float64
	// Clip ограничивает отрисовку прямоугольником, Unclip снимает ограничение.
	Clip(r Rect)
	Unclip()
	// Px переводит логические точки в пиксели, Scale — их отношение.
	Px(v int32) int32
	Scale() float64
	// FillPixels закрашивает прямоугольник, заданный прямо в пикселях.
	FillPixels(x, y, w, h int32, c Color)
	// DrawImage кладёт картинку с прозрачностью в прямоугольник r. Картинка уже
	// должна быть размером Px(r.W)×Px(r.H) — холст её не масштабирует, а
	// переносит пиксель в пиксель (см. LogoPixels). Один и тот же указатель
	// означает одну и ту же картинку: реализация вправе это кешировать.
	DrawImage(r Rect, img *image.RGBA)
}

// Align — выравнивание текста внутри его прямоугольника.
type Align int

const (
	AlignLeft Align = iota
	AlignCenter
	AlignRight
)
