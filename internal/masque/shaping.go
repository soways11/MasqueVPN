package masque

import "time"

// Shaping управляет формой исходящего трафика (защита от анализа по размеру и
// таймингу). Все поля необязательны; nil-функции означают «без изменений».
// Конкретные политики строит пакет internal/obfuscation.
type Shaping struct {
	// Pad возвращает целевую длину поля IP-пакета в датаграмме для реального
	// пакета длиной realLen. Если результат больше realLen — добавляется паддинг,
	// который получатель обрезает по длине из IP-заголовка. Меньшие значения
	// игнорируются (пакет не режется).
	Pad func(realLen int) int

	// Delay возвращает задержку перед отправкой пакета (джиттер).
	// Применяйте небольшие значения и, как правило, только к мелким пакетам,
	// чтобы не ломать задержки основного трафика.
	Delay func(realLen int) time.Duration

	// Cover, если задан, включает фоновую отправку маскирующих датаграмм в простое.
	Cover *CoverConfig
}

// CoverConfig описывает маскирующий (cover) трафик.
//
// Интервал задаётся ФУНКЦИЕЙ, а не константой, и это принципиально: cover через
// фиксированный период — это метроном, то есть ровно тот признак регулярности,
// от которого мы защищаемся. Пакет obfuscation отдаёт пуассоновские интервалы.
type CoverConfig struct {
	// Next возвращает паузу до следующей попытки. Если за эту паузу ничего не
	// было отправлено, уходит одна cover-датаграмма.
	Next func() time.Duration
	// Size возвращает размер полезной нагрузки очередной cover-датаграммы (байт).
	Size func() int
	// Always — слать cover и под нагрузкой, а не только в простое.
	//
	// Зачем: у браузера фоновые обращения идут всегда, а не замирают, пока
	// пользователь что-то качает. Если cover появляется ровно в паузах, то
	// сам факт «пошёл cover» размечает наблюдателю границы активности —
	// признак, который мы этим cover и собирались закрыть.
	Always bool
}

func (s *Shaping) padTo(realLen int) int {
	if s == nil || s.Pad == nil {
		return 0
	}
	return s.Pad(realLen)
}

func (s *Shaping) delay(realLen int) time.Duration {
	if s == nil || s.Delay == nil {
		return 0
	}
	return s.Delay(realLen)
}
