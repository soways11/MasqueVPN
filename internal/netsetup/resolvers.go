package netsetup

import "net/netip"

// UsableResolver отсеивает адреса, которые система показывает в списке
// серверов DNS, но резолверами не являются.
//
// Главный случай — fec0:0:0:ffff::1..3. Windows держит эту тройку у каждого
// адаптера как заглушку «серверы по умолчанию»; это site-local адреса из
// отменённого RFC 3879, и по ним никто никогда не отвечает. Принять их за
// настоящие резолверы значит слать прикрытие DNS в пустоту и, хуже того,
// пытаться уводить маршруты к ним мимо туннеля — с предупреждением в
// журнале, из которого нельзя понять, что всё в порядке.
//
// Петлевые адреса отсеиваются по другой причине: локальный резолвер (systemd
// -resolved, Pi-hole на самой машине) для прикрытия бесполезен — запрос до
// сети не дойдёт, а смысл прикрытия в том, чтобы его было видно снаружи.
func UsableResolver(a netip.Addr) bool {
	if !a.IsValid() || a.IsUnspecified() || a.IsLoopback() || a.IsLinkLocalUnicast() {
		return false
	}
	if a.Is6() {
		b := a.As16()
		if b[0] == 0xfe && b[1]&0xc0 == 0xc0 { // fec0::/10, site-local
			return false
		}
	}
	return true
}
