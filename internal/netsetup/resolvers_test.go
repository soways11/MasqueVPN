package netsetup

import (
	"net/netip"
	"testing"
)

// Прикрытие DNS существует ради одного: чтобы снаружи хост выглядел как
// обычная машина, которая спрашивает имена. Запрос, ушедший в адрес, по
// которому никого нет, этой задачи не решает — снаружи его просто не видно,
// а мы считаем, что прикрытие работает.
//
// Windows держит у каждого адаптера тройку fec0:0:0:ffff::1..3 как заглушку
// «серверы по умолчанию». Это site-local адреса из отменённого RFC 3879, и
// отвечать по ним некому. На живой машине они оказались первыми тремя из
// четырёх «резолверов системы», а четвёртым — настоящий роутер.
func TestWindowsPlaceholderResolversAreNotResolvers(t *testing.T) {
	for _, s := range []string{
		"fec0:0:0:ffff::1", "fec0:0:0:ffff::2", "fec0:0:0:ffff::3",
	} {
		if UsableResolver(netip.MustParseAddr(s)) {
			t.Errorf("%s принят за резолвер: прикрытие уйдёт в пустоту, "+
				"а маршрут к нему будет напрасно уводиться мимо туннеля", s)
		}
	}
}

func TestRealResolversAreKept(t *testing.T) {
	for _, s := range []string{
		"192.168.1.1",          // домашний роутер — обычный случай
		"8.8.8.8",              // публичный
		"2001:4860:4860::8888", // публичный IPv6
		"fd00::1",              // ULA: чей-то локальный резолвер, но живой
	} {
		if !UsableResolver(netip.MustParseAddr(s)) {
			t.Errorf("%s отброшен, хотя это настоящий резолвер", s)
		}
	}
}

// Локальный резолвер для прикрытия бесполезен: запрос не выйдет в сеть, а
// смысл прикрытия в том, чтобы его было видно снаружи.
func TestLocalAndUnusableAddressesAreDropped(t *testing.T) {
	for _, s := range []string{
		"127.0.0.1", "::1", // петлевые
		"169.254.1.1", "fe80::1", // link-local
		"0.0.0.0", "::", // неопределённые
	} {
		if UsableResolver(netip.MustParseAddr(s)) {
			t.Errorf("%s принят за резолвер прикрытия", s)
		}
	}
	if UsableResolver(netip.Addr{}) {
		t.Error("пустой адрес принят за резолвер")
	}
}
