package netsetup

// Адресная арифметика аварийного отключения. Вынесена из файла с WFP (только
// Windows), потому что именно здесь ошибка тише всего: неверный порядок байт
// или маска очертят разрешающий фильтр не по той подсети — и либо в дыру
// утечёт трафик, либо машину отрежет от собственной сети. Чистые функции,
// проверяются тестом на любой платформе.

// beToHost переводит 4 байта адреса (сетевой порядок) в UINT32 порядка хоста,
// как того ждёт FWP_V4_ADDR_AND_MASK.
func beToHost(a [4]byte) uint32 {
	return uint32(a[0])<<24 | uint32(a[1])<<16 | uint32(a[2])<<8 | uint32(a[3])
}

// prefixMask4 — маска подсети из длины префикса: 24 → 0xffffff00.
func prefixMask4(bits int) uint32 {
	if bits <= 0 {
		return 0
	}
	if bits >= 32 {
		return 0xffffffff
	}
	return ^uint32(0) << (32 - bits)
}
