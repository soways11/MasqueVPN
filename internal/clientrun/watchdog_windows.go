//go:build windows

package clientrun

// Сторож: процесс, который убирает за клиентом, если тот не дожил до выхода.
//
// # Почему без него не обойтись
//
// Клиент правит в системе три вещи. Блокировку WFP мы научили умирать
// вместе с процессом — она живёт в динамической сессии. А правило
// разрешения имён (NRPT) лежит в реестре, и маршрут-исключение — в таблице
// маршрутизации ядра: обоим всё равно, жив ли тот, кто их создал.
//
// Снять их может только код, который выполнится ПОСЛЕ смерти клиента.
// Внутри самого клиента такого места нет: снятую задачу не предупреждают,
// defer не выполняется, обработчик не зовётся. Уборка при следующем
// запуске помогает, но между крахом и запуском можно просидеть сколько
// угодно — а всё это время системный DNS уходит на резолвер за туннелем,
// которого уже нет. На живой машине это выглядело как «обычный интернет
// работает, а часть соединений не устанавливается».
//
// Поэтому клиент, подняв полный туннель, запускает вторую копию себя с
// флагом -watchdog: она ничего не делает, только ждёт смерти родителя и
// прибирается. При штатном выходе клиент убирает сам и гасит сторожа.
//
// # Чего сторож не может
//
// Если снять обе задачи разом, убирать снова будет некому — тогда следы
// уберёт запуск клиента или команда -cleanup. Поэтому сторож запускается
// отдельным процессом, не входящим в группу родителя (DETACHED_PROCESS):
// так «снять задачу» на дереве процессов клиента его не задевает.

import (
	"fmt"
	"os"
	"os/exec"

	"golang.org/x/sys/windows"

	"github.com/soways11/masquevpn/internal/netsetup"
)

// WatchdogFlag — имя флага, которым запускается сторож.
const WatchdogFlag = "watchdog"

// StartWatchdog запускает сторожа, следящего за текущим процессом.
// Возвращает функцию остановки: её вызывают при ШТАТНОМ выходе, когда
// клиент уже прибрался сам.
func StartWatchdog() (stop func(), err error) {
	exe, err := os.Executable()
	if err != nil {
		return nil, err
	}
	cmd := exec.Command(exe, "-"+WatchdogFlag, fmt.Sprint(os.Getpid()))
	cmd.SysProcAttr = &windows.SysProcAttr{
		HideWindow: true,
		// DETACHED_PROCESS: у сторожа нет консоли и он не входит в группу
		// процессов клиента — иначе «снять задачу» убило бы и его.
		CreationFlags: windows.DETACHED_PROCESS | windows.CREATE_NEW_PROCESS_GROUP,
	}
	if err := cmd.Start(); err != nil {
		return nil, err
	}
	proc := cmd.Process
	return func() {
		if proc != nil {
			_ = proc.Kill()
			_, _ = proc.Wait()
		}
	}, nil
}

// RunWatchdog — тело сторожа: дождаться смерти процесса pid и прибраться.
//
// Возвращает отчёт уборки. Если процесс уже мёртв (клиент успел умереть,
// пока сторож запускался), уборка делается сразу.
func RunWatchdog(pid int) (netsetup.CleanupReport, error) {
	h, err := windows.OpenProcess(windows.SYNCHRONIZE, false, uint32(pid))
	if err == nil {
		defer windows.CloseHandle(h)
		// Ждём столько, сколько живёт клиент: у сторожа нет других дел.
		_, _ = windows.WaitForSingleObject(h, windows.INFINITE)
	}
	return netsetup.Cleanup()
}
